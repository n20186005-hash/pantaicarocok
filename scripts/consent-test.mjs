import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const readScript = path => readFileSync(path, 'utf8').match(/<script is:inline>([\s\S]*?)<\/script>/)[1];
const inputs = { analytics: { checked: false }, preferences: { checked: false } };
const status = {};
const form = { elements: { namedItem: key => inputs[key] }, addEventListener(event, fn) { this.submit = fn; } };
const loaded = [];
const context = { window: {}, localStorage: { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); }, removeItem() { throw Error('blocked'); } }, document: { documentElement: { lang: 'en' }, querySelector: key => key === '[data-cookie-controls]' ? form : key === '.cookie-status' ? status : loaded[0], createElement: () => ({ dataset: {} }), head: { appendChild: s => loaded.push(s) } } };
vm.runInNewContext(readScript('src/layouts/Base.astro'), context);
vm.runInNewContext(readScript('src/components/LegalPage.astro'), context);
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], true);
assert.equal(loaded.length, 0);
assert.equal(inputs.analytics.checked, false);
inputs.analytics.checked = true;
form.submit({ preventDefault() {} });
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], false);
assert.equal(loaded.length, 1);
assert.match(status.textContent, /could not be saved/);
inputs.analytics.checked = false;
form.submit({ preventDefault() {} });
assert.equal(context.window['ga-disable-G-HXM22WWPKP'], true);
assert.equal(loaded.length, 1);
assert.match(status.textContent, /could not be saved/);
console.log('Consent: blocked storage, explicit grant, immediate refusal and truthful persistence status passed.');
